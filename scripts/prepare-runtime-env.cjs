const fs = require('node:fs');
const path = require('node:path');

const projectRoot = path.join(__dirname, '..');
const outputPath = path.join(projectRoot, 'build', 'runtime', 'runtime.env');
const envFiles = ['.env', '.env.local'];
const runtimeKeys = [
  'VITE_KUGOU_API_BASE',
  'VITE_NETEASE_API_BASE',
  'VITE_API_TIMEOUT',
  'VITE_KUGOU_API_TARGET',
  'VITE_NETEASE_API_TARGET',
  'VITE_DEV_SERVER_URL',
  'VITE_DEV_SERVER_PORT',
  'KUGOU_API_TARGET',
  'NETEASE_API_TARGET',
];

const values = envFiles.reduce(
  (env, fileName) => ({
    ...env,
    ...readEnvFile(path.join(projectRoot, fileName)),
  }),
  {},
);
const missingTargets = ['VITE_KUGOU_API_TARGET', 'VITE_NETEASE_API_TARGET']
  .filter((key) => !values[key] && !values[key.replace('VITE_', '')]);
const lines = [
  '# Generated by scripts/prepare-runtime-env.cjs.',
  '# Do not commit this file.',
  ...runtimeKeys.map((key) => `${key}=${values[key] ?? ''}`),
];

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, `${lines.join('\n')}\n`, 'utf8');

if (missingTargets.length) {
  console.warn(
    `Runtime env prepared, but missing API target values: ${missingTargets.join(', ')}`,
  );
} else {
  console.log('Runtime env prepared for desktop build.');
}

function readEnvFile(filePath) {
  let content = '';

  try {
    content = fs.readFileSync(filePath, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') {
      console.warn(`Failed to read env file: ${filePath}`);
    }

    return {};
  }

  return content
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line && !line.startsWith('#'))
    .reduce((env, line) => {
      const separatorIndex = line.indexOf('=');

      if (separatorIndex <= 0) {
        return env;
      }

      const key = line.slice(0, separatorIndex).trim();
      const value = normalizeEnvValue(line.slice(separatorIndex + 1));

      if (key) {
        env[key] = value;
      }

      return env;
    }, {});
}

function normalizeEnvValue(rawValue = '') {
  const value = rawValue.trim();
  const quote = value[0];

  if (
    (quote === '"' || quote === "'") &&
    value.length >= 2 &&
    value[value.length - 1] === quote
  ) {
    return value.slice(1, -1);
  }

  return value;
}
